import {workerData} from 'node:worker_threads';
import pg from 'pg';
import {translateSql,sqlParts} from './database-sql.mjs';
const {port,signal,connectionString,schema}=workerData;
const state=new Int32Array(signal);
pg.types.setTypeParser(20,value=>{const n=Number(value);if(!Number.isSafeInteger(n))throw Error('PostgreSQL integer exceeds the API safe integer range');return n;});
pg.types.setTypeParser(1700,value=>{const n=Number(value);if(!Number.isFinite(n)||Math.abs(n)>Number.MAX_SAFE_INTEGER)throw Error('PostgreSQL numeric exceeds the API safe number range');return n;});
const client=new pg.Client({connectionString,application_name:'volna',connectionTimeoutMillis:10000,statement_timeout:30000});
let closed=false;
const identities=new Set();
const respond=value=>{port.postMessage(value);Atomics.store(state,0,1);Atomics.notify(state,0);};
try {
 await client.connect();
 if(schema){if(!/^volna_test_[a-f0-9]+$/.test(schema))throw Error('Invalid test schema');await client.query(`CREATE SCHEMA IF NOT EXISTS "${schema}"`);await client.query(`SET search_path TO "${schema}", public`);}
 await client.query(`CREATE OR REPLACE FUNCTION volna_instr(text,text) RETURNS integer LANGUAGE sql IMMUTABLE STRICT AS 'SELECT strpos($1,$2)';
 CREATE OR REPLACE FUNCTION volna_casefold(text) RETURNS text LANGUAGE sql IMMUTABLE AS 'SELECT lower(COALESCE($1,''''))';`);
 const previous=(await client.query("SELECT table_name FROM information_schema.columns WHERE table_schema=current_schema() AND is_identity='YES' AND column_name='id'")).rows;
 previous.forEach(r=>identities.add(r.table_name));respond({ready:true});
} catch(e){respond({error:{message:'Cannot initialize PostgreSQL connection',code:e.code||'PG_CONNECTION_FAILED'}});await client.end().catch(()=>{});port.close();}
async function query(source,params=[],mode='all') {
 let sql=translateSql(source);
 const table=sql.match(/^CREATE TABLE (?:IF NOT EXISTS )?(\w+)/i);
 if(table&&/\bid BIGINT GENERATED BY DEFAULT AS IDENTITY/.test(sql))identities.add(table[1]);
 const insert=sql.match(/^INSERT INTO (\w+)/i);
 if(insert&&identities.has(insert[1])&&!/\bRETURNING\b/i.test(sql))sql+=' RETURNING id';
 const result=await client.query(sql,params);
 if(mode==='run')return {changes:result.rowCount||0,lastInsertRowid:result.rows[0]?.id||0};
 return result.rows;
}
port.on('message',async request=>{
 try{
  let result;
  if(request.op==='close'){closed=true;await client.end();result=null;}
  else if(request.op==='exec'){for(const sql of sqlParts(request.sql))await query(sql);result=null;}
  else result=await query(request.sql,request.params,request.op);
  respond({result});if(closed)port.close();
 }catch(e){respond({error:{message:e.code==='23505'?'UNIQUE constraint violation':e.message,code:e.code,detail:undefined}});}
});
