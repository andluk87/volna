// Transitional SQL dialect boundary. All storage and transactions are PostgreSQL.
// Keep the existing synchronous service contracts until they can be made async.
export function sqlParts(source) {
  const parts=[];let start=0,quote=null;
  for(let i=0;i<source.length;i++){
    if(quote?.startsWith('$')){if(source.startsWith(quote,i)){i+=quote.length-1;quote=null;}continue;}
    if(quote){if(source[i]===quote){if(source[i+1]===quote)i++;else quote=null;}continue;}
    if(source[i]==='$'){const tag=source.slice(i).match(/^\$(?:[a-zA-Z_][a-zA-Z0-9_]*)?\$/)?.[0];if(tag){quote=tag;i+=tag.length-1;continue;}}
    if(source[i]==="'"||source[i]==='"'){quote=source[i];continue;}
    if(source[i]===';'){parts.push(source.slice(start,i).trim());start=i+1;}
  }
  parts.push(source.slice(start).trim());return parts.filter(Boolean);
}
export function translateSql(source) {
  // Protect literals before rewriting identifiers, types, functions and parameters.
  const literals=[];
  if(/^(CREATE OR REPLACE FUNCTION|CREATE TRIGGER|DROP TRIGGER)\b/i.test(source))return source;
  let sql=source.replace(/'(?:''|[^'])*'/g,s=>`__literal_${literals.push(s)-1}__`);
  sql=sql.replace(/\bBEGIN IMMEDIATE\b/gi,'BEGIN');
  sql=sql.replace(/\bINTEGER PRIMARY KEY(?: AUTOINCREMENT)?/gi,'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  sql=sql.replace(/\bINTEGER\b/gi,'BIGINT').replace(/\bREAL\b/gi,'DOUBLE PRECISION').replace(/\bBLOB\b/gi,'BYTEA');
  // SQLite's scalar min/max differ from aggregate min/max.
  const scalar=/\b(MAX|MIN)\s*\(/gi;let match;
  const replacements=[];
  while((match=scalar.exec(sql))){let depth=1,comma=false;for(let i=scalar.lastIndex;i<sql.length&&depth;i++){if(sql[i]==='(')depth++;else if(sql[i]===')')depth--;else if(sql[i]===','&&depth===1)comma=true;}if(comma)replacements.push([match.index,match[1].length,match[1].toUpperCase()==='MAX'?'GREATEST':'LEAST']);}
  for(const [i,n,value] of replacements.reverse())sql=sql.slice(0,i)+value+sql.slice(i+n);
  sql=sql.replace(/\bIS\s+\?/gi,'IS NOT DISTINCT FROM ?');
  sql=sql.replace(/\bjson_each\(([^)]+)\)\s+(\w+)/gi,'jsonb_array_elements_text(($1)::jsonb) AS $2(value)');
  sql=sql.replace(/LEFT JOIN (jsonb_array_elements_text\([^;]+? AS \w+\(value\)) WHERE/gi,'LEFT JOIN LATERAL $1 ON TRUE WHERE');
  sql=sql.replace(/\b(instr|casefold)\s*\(/gi,'volna_$1(');
  if(/^INSERT OR IGNORE\b/i.test(sql)){sql=sql.replace(/^INSERT OR IGNORE/i,'INSERT');sql+=' ON CONFLICT DO NOTHING';}
  let index=0;sql=sql.replace(/\?/g,()=>'$'+(++index));
  sql=sql.replace(/__literal_(\d+)__/g,(_,i)=>literals[Number(i)]);
  sql=sql.replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g,`to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`);
  return sql;
}
